public class CalccBasic   {
    int addDigits(int a ,int b){
        int result=a+b;
        return result;
    }

    int addDigits(int a ,int b,int c){
        int result=a+b+c;
        return result;
    }
    int sub(int a ,int b,int c){
        int result=a+b-c;
        return  result;
    }
}
